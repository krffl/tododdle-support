#!/usr/bin/env node
// Copies the repository version from /VERSION into every SDK: npm packages, Swift, Flutter.
// Kotlin reads /VERSION at build time.
// Run `node scripts/sync-version.mjs` after changing /VERSION, or `--check` to verify in CI.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = readFileSync(join(root, 'VERSION'), 'utf8').trim();
const check = process.argv.includes('--check');
const problems = [];

function update(relativePath, transform) {
  const path = join(root, relativePath);
  const before = readFileSync(path, 'utf8');
  const after = transform(before);
  if (before === after) return;
  if (check) problems.push(relativePath);
  else writeFileSync(path, after);
}

const corePackage = '@krffl/tododdle-support';

for (const pkg of ['packages/js/package.json', 'packages/react-native/package.json']) {
  update(pkg, (text) => {
    const json = JSON.parse(text);
    json.version = version;
    if (json.dependencies?.[corePackage]) json.dependencies[corePackage] = version;
    return `${JSON.stringify(json, null, 2)}\n`;
  });
}

update(
  'packages/js/src/version.ts',
  () =>
    `// Generated by scripts/sync-version.mjs from /VERSION. Do not edit.\nexport const SDK_VERSION = '${version}';\n`,
);

update('swift/Sources/TododdleSupport/SDKVersion.swift', (text) =>
  text.replace(/(public static let sdkVersion = ")[^"]*(")/, `$1${version}$2`),
);

update('flutter/pubspec.yaml', (text) => text.replace(/^version: .*$/m, `version: ${version}`));

update('flutter/lib/src/version.dart', (text) =>
  text.replace(/(const String tododdleSupportSdkVersion = ')[^']*(')/, `$1${version}$2`),
);

if (problems.length > 0) {
  console.error(`Version ${version} from /VERSION is not applied to: ${problems.join(', ')}`);
  console.error('Run `npm run sync-version`.');
  process.exit(1);
}
console.log(check ? `Version ${version} is in sync.` : `Applied version ${version}.`);
